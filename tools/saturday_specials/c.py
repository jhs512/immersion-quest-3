def make(id, title, principle, goal, body, before, after, *, methods='', caution, challenge=False):
    source = '#include <stdio.h>\n#include <stdlib.h>\n' + code(methods) + '\n' if methods else '#include <stdio.h>\n#include <stdlib.h>\n'
    if 'malloc(' not in body + methods and 'free(' not in body + methods:
        source = source.replace('#include <stdlib.h>\n', '')
    source += 'int main(void) {\n    // 입력값을 바꿔도 같은 원리로 풀어요.\n    int a, b;\n    if (scanf("%d %d", &a, &b) != 2) return 1;\n'
    source += ''.join('    ' + line + '\n' for line in code(body).replace('\n"', '\\n"').splitlines())
    source += '    return 0;\n}\n'
    t = task(id, title, principle, goal, source, before, after, language='c',
             tests=[(i, '') for i in INPUTS], caution=caution, challenge=challenge,
             hints=['변수 칸과 그 칸을 가리키는 화살표를 그려 보세요.', after.strip()])
    t['entry_file'] = 'main.c'
    return t


