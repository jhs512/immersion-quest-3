def rewrite(lesson, out):
    """Keep verified edit/run steps; replace template speech with authored reasoning."""
    scripts = SCRIPTS[lesson['id']]
    assert set(scripts) == {t['id'] for t in lesson['tasks']}
    lesson['revision'] = 'v1.0.1'
    for task in lesson['tasks']:
        before, change, after = scripts[task['id']]
        for text in (before, change, after):
            assert all(len(s) <= 45 for s in re.split(r'(?<=[.?!])\s+', text)), (task['id'], text)
            assert not any(mark in text for mark in ('실행 결과를 비교해요.', ' / ', '작은 부분을 바꿔 원리를 확인해요.'))
        actions = task['narration']
        readings = [a for a in actions if a['action'] == 'say' and a.get('target') == 'output']
        assert len(readings) == 2
        readings[0]['text'], readings[1]['text'] = before, after
        for action in actions:
            if action['action'] == 'set_code': action['say'] = '먼저 준비 코드를 실행해 볼게요.'
            if action['action'] == 'patch_code': action['say'] = change
        # The cache records both the verified executable steps and authored text.
    from saturday_specials.tutor import enrich
    enrich(lesson)
    for task in lesson['tasks']:
        actions = task['narration']
        fingerprint = hashlib.sha256(json.dumps(task, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
        folder = Path(out) / 'narration-cache'
        folder.mkdir(parents=True, exist_ok=True)
        (folder / f"{lesson['id']}--{task['id']}.json").write_text(json.dumps(
            dict(hash=fingerprint, by='authored-reasoning-v1', actions=actions), ensure_ascii=False, indent=2), encoding='utf8')
