CASES = [{'n': '5'}, {'n': '9'}]


def make(id, title, principle, goal, body, methods, before, after, *, caution, challenge=False):
    source = main_class('// 이번 실험의 시작값이에요.\nint n = 3;\n' + body, methods)
    return java_task(id, title, principle, goal, source, before, after,
        scenarios=CASES, caution=caution, hints=[
            '실행 전에 클래스 칸과 객체별 칸을 따로 적어 보세요.',
            chr(96) + after.strip() + chr(96)], challenge=challenge)


