// Exercise our own app's real WebView, without submitting fabricated learning progress.
const {chromium}=require('../target/ui-tests/node_modules/playwright-core');
const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
(async()=>{
 const b=await chromium.connectOverCDP('http://127.0.0.1:9229');
 const p=b.contexts()[0].pages()[0];p.setDefaultTimeout(60000);
 if(await p.getByRole('button',{name:'← 코스 수업 목록',exact:true}).count())await p.getByRole('button',{name:'← 코스 수업 목록',exact:true}).click();
 await p.getByRole('button',{name:'코스 추가·만들기',exact:true}).waitFor();
 await p.getByRole('button',{name:'코스 추가·만들기',exact:true}).click();
 await p.getByLabel('코스 저장소 · owner/repository',{exact:true}).fill('jhs512/mq3-course-java-principles');
 await p.getByRole('button',{name:'코스 불러오기',exact:true}).click();
 await p.locator('.lesson-card').filter({hasText:'직접 바꾸며 이해하는 출력과 계산'}).waitFor();
 assert.equal(await p.getByRole('button',{name:'복습모드 시작',exact:true}).count(),0);
 await p.getByRole('button',{name:'학습 시작',exact:true}).click();
 await p.locator('.repository-task .cm-editor').waitFor();
 assert.equal(await p.locator('.study-navigation button').count(),10);
 assert.equal(await p.locator('.repository-reading').count(),0);
 const col=p.getByRole('separator',{name:'문제와 코드 패널 크기 조절'});
 const row=p.getByRole('separator',{name:'코드와 실행 결과 패널 크기 조절'});
 let width=await p.locator('.problem-pane').evaluate(n=>n.getBoundingClientRect().width);
 await col.focus();await col.press('ArrowRight');
 assert.ok(await p.locator('.problem-pane').evaluate(n=>n.getBoundingClientRect().width)>width);
 const box=await col.boundingBox();width=await p.locator('.problem-pane').evaluate(n=>n.getBoundingClientRect().width);
 await p.mouse.move(box.x+box.width/2,box.y+box.height/2);await p.mouse.down();
 await p.mouse.move(box.x+box.width/2+45,box.y+box.height/2);await p.mouse.up();
 assert.ok(await p.locator('.problem-pane').evaluate(n=>n.getBoundingClientRect().width)>width+25);
 let height=await p.locator('.editor-pane').evaluate(n=>n.getBoundingClientRect().height);
 await row.focus();await row.press('ArrowUp');
 assert.ok(await p.locator('.editor-pane').evaluate(n=>n.getBoundingClientRect().height)<height);
 assert.equal(await p.locator('.problem-pane').evaluate(n=>getComputedStyle(n).scrollbarWidth),'thin');
 await col.dblclick();await row.dblclick();
 const lesson=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../target/principles-course/lesson.json'),'utf8'));
 await p.evaluate(s=>window.molipCodeEditors.setValue(s),lesson.tasks[0].solution);
 await p.getByRole('button',{name:'코드 실행',exact:true}).click();
 await p.waitForFunction(()=>document.querySelector('.execution-status')?.textContent.includes('실행 완료'));
 assert.match(await p.locator('.result-pane .output').innerText(),/시작!/);
 await p.getByRole('button',{name:'다음 문제 →',exact:true}).click();
 await p.locator('.problem-pane h2').filter({hasText:'줄은 언제 바뀔까요?'}).waitFor();
 await p.getByRole('button',{name:'← 이전 문제',exact:true}).click();
 await p.waitForFunction(s=>window.molipCodeEditors.getValue()===s,lesson.tasks[0].solution);
 assert.equal(await p.evaluate(()=>window.molipCodeEditors.getValue()),lesson.tasks[0].solution);
 // Leave the lesson ready for the human, with its original experiment code.
 await p.getByRole('button',{name:'초기화',exact:true}).click();
 await p.waitForFunction(s=>window.molipCodeEditors.getValue()===s,lesson.tasks[0].starter_code);
 const out=path.resolve(__dirname,'../target/principles-ui');fs.mkdirSync(out,{recursive:true});
 await p.screenshot({path:path.join(out,'first-lesson.png'),fullPage:true});
 console.log('PASS new course, optional review, 10 tasks, keyboard + drag resizing, thin scrollbars, real Java run, navigation + drafts');
 console.log('Issue:',await p.getByRole('link',{name:'내 진도 이슈',exact:true}).getAttribute('href'));
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
