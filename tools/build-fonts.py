"""Regenerate assets/fonts/fonts.css from the woff2 files next to it (base64 @font-face rules)."""
import base64
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1] / "assets" / "fonts"
def face(family, file, weight):
    data = base64.b64encode((ROOT / file).read_bytes()).decode()
    return f"@font-face {{ font-family: '{family}'; src: url(data:font/woff2;base64,{data}) format('woff2'); font-weight: {weight}; font-style: normal; font-display: swap; }}\n"
css = "/* Bundled fonts: Pretendard (OFL) for text, D2Coding (OFL) for code. Generated by tools/build-fonts.py. */\n"
css += face("Pretendard", "PretendardVariable.woff2", "45 920")
css += face("D2Coding", "D2Coding-Regular.woff2", "400")
(ROOT / "fonts.css").write_text(css, encoding="utf-8")
print("fonts.css", len(css) // 1024, "KB")
