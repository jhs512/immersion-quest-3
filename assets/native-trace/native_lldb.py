"""Record an unmodified C++ or Rust debug binary through LLDB: real stops, real memory, one run.

Values come from LLDB's typed view of the process (with rustc's own LLDB formatters for Rust). For Rust, a binding
whose value was moved out still has its old bytes on the stack; `rust_mir.py` events from the same compiler decide
that it is moved, and it is drawn as a note, never as a live value.
"""
import json
import math
import os
import re
import shlex

import lldb


LIMIT = 1000
HITS = 20000
MAX_CHILDREN = 64
DEPTH = 64
ALLOCATORS = {'malloc': 'alloc', 'calloc': 'calloc', 'realloc': 'realloc', 'free': 'free',
              'malloc_type_malloc': 'alloc', 'malloc_type_calloc': 'calloc', 'malloc_type_realloc': 'realloc',
              '_Znwm': 'alloc', '_ZnwmSt19__type_descriptor_t': 'alloc', '_ZnamSt19__type_descriptor_t': 'alloc', '_Znam': 'alloc', '_ZdlPv': 'free', '_ZdlPvm': 'free', '_ZdaPv': 'free', '_ZdaPvm': 'free'}
RUST_NAMES = [('unsigned char', 'u8'), ('signed char', 'i8'), ('unsigned short', 'u16'), ('short', 'i16'),
              ('unsigned int', 'u32'), ('int', 'i32'), ('unsigned long', 'u64'), ('long', 'i64'),
              ('unsigned __int128', 'u128'), ('__int128', 'i128'), ('float', 'f32'), ('double', 'f64')]
MOVED = '옮겨진 값(move) · 이 이름으로는 더 쓸 수 없어요'


def _read(path):
    try:
        with open(path, 'rb') as stream:
            return stream.read().decode('utf-8', 'replace').replace('\r\n', '\n')
    except FileNotFoundError:
        return ''


def _load(path, default):
    return json.loads(_read(path)) if os.path.isfile(path) else default


def _unquote(summary):
    """LLDB's C-style quoted string summary ("a\\n") to its text, or None."""
    if not summary or len(summary) < 2 or summary[0] != '"' or summary[-1] != '"':
        return None
    out, body, i = [], summary[1:-1], 0
    escapes = {'n': '\n', 't': '\t', 'r': '\r', '0': '\0', '\\': '\\', '"': '"', "'": "'", 'a': '\a', 'b': '\b',
               'f': '\f', 'v': '\v', 'e': '\x1b'}
    while i < len(body):
        c = body[i]
        if c != '\\' or i + 1 == len(body):
            out.append(c)
            i += 1
            continue
        nxt = body[i + 1]
        if nxt == 'x':
            match = re.match(r'[0-9a-fA-F]{1,2}', body[i + 2:])
            if not match:
                return None
            out.append(chr(int(match.group(), 16)))
            i += 2 + len(match.group())
        elif nxt == 'u' and body[i + 2:i + 3] == '{':
            end = body.index('}', i)
            out.append(chr(int(body[i + 3:end], 16)))
            i = end + 1
        elif nxt in escapes:
            out.append(escapes[nxt])
            i += 2
        else:
            return None
    return ''.join(out)


class Recorder:
    def __init__(self, target, case, language, source_name):
        self.target = target
        self.process = None
        self.case = case
        self.rust = language == 'rust'
        self.source_name = source_name
        self.blocks = {}
        self.freed = {}
        self.serial = 0
        self.pending = {}
        self.returning = {}
        self.return_addresses = set()
        self.allocator_ids = {}
        self.frame_ids = {}
        self.next_frame = 1
        self.live_frames = set()
        self.truncated = False
        self.view_ids = {}
        self.next_view = 1
        self.declarations = _load(os.path.join(case, 'declarations.json'), {})
        facts = _load(os.path.join(case, 'moves.json'), {})
        self.moves = facts.get('events', {})
        self.entries = facts.get('entries', {})
        self.hidden = set(facts.get('hidden', []))
        self.lines = _read(os.path.join(case, source_name)).splitlines()
        self.ownership = {}
        self.frame_lines = {}
        self.arm = target.GetTriple().startswith(('arm64', 'aarch64'))
        if not self.rust:
            # C++ only: Rust's safe code cannot keep a pointer to freed memory, so its heap is drawn from owners.
            for name in ALLOCATORS:
                breakpoint = target.BreakpointCreateByName(name, lldb.eFunctionNameTypeFull | lldb.eFunctionNameTypeBase,
                                                           lldb.SBFileSpecList(), lldb.SBFileSpecList())
                self.allocator_ids[breakpoint.GetID()] = name

    def register(self, frame, index, returning=False):
        if self.arm:
            name = 'x0' if returning else 'x' + str(index)
        else:
            name = 'rax' if returning else ('rdi', 'rsi')[index]
        return frame.FindRegister(name).GetValueAsUnsigned()

    def user_frame(self, frame):
        entry = frame.GetLineEntry()
        if not entry.IsValid() or entry.GetFileSpec().GetFilename() != self.source_name:
            return False
        # Code generated by #[derive(...)] is attributed to the attribute line; it is not the learner's code.
        return not (self.rust and self.lines[self.start_line(frame) - 1:][:1] and
                    self.lines[self.start_line(frame) - 1].lstrip().startswith('#['))

    def start_line(self, frame):
        return frame.GetFunction().GetStartAddress().GetLineEntry().GetLine() if frame.GetFunction().IsValid() else 0

    def type_key(self, typ):
        return typ.GetCanonicalType().GetUnqualifiedType().GetName()

    def object_id(self, key):
        if key not in self.view_ids:
            self.view_ids[key] = self.next_view
            self.next_view += 1
        return str(self.view_ids[key])

    def pretty(self, name):
        name = name or ''
        if self.rust:
            name = re.sub(r', alloc::alloc::Global>', '>', name)
            name = re.sub(r'\b(?:alloc|core|std)::(?:[a-z_][a-z0-9_]*::)*', '', name)
            name = re.sub(r'\b[a-z_][a-z0-9_]*::(?=[A-Z])', '', name)
            for c_name, rust_name in RUST_NAMES:
                name = re.sub(r'(?<![\w:])' + c_name + r'(?![\w])', rust_name, name)
            return re.sub(r'^(.*) \*$', r'&', name)
        name = re.sub(r'std::__(?:cxx11|1)::', 'std::', name)
        name = re.sub(r', std::allocator<[^<>]*(?:<[^<>]*>)?\s*>', '', name)
        name = name.replace('std::basic_string<char, std::char_traits<char> >', 'std::string')
        return name.replace(' >', '>')

    # Allocation tracking (C++). Blocks remember whether user code asked for them.
    def allocator_stop(self, thread):
        frame = thread.GetFrameAtIndex(0)
        key = (thread.GetThreadID(), frame.GetPC())
        if key in self.pending:
            kind, size, old, user = self.pending.pop(key)
            address = self.register(frame, 0, True)
            if kind == 'realloc' and old in self.blocks and (address or size == 0):
                self.freed[old] = self.blocks.pop(old)
            if address:
                self.serial += 1
                self.freed.pop(address, None)
                self.blocks[address] = (size, self.serial, user)
            return True
        for index in range(thread.GetStopReasonDataCount() // 2):
            name = self.allocator_ids.get(thread.GetStopReasonDataAtIndex(index * 2))
            if not name:
                continue
            kind = ALLOCATORS[name]
            caller = thread.GetFrameAtIndex(1)
            first = self.register(frame, 0)
            if kind == 'free':
                if first in self.blocks:
                    self.freed[first] = self.blocks.pop(first)
                return True
            second = self.register(frame, 1) if kind in ('calloc', 'realloc') else 0
            size = first * second if kind == 'calloc' else second if kind == 'realloc' else first
            at = caller.GetPC()
            self.target.BreakpointCreateByAddress(at).SetOneShot(True)
            self.pending[(thread.GetThreadID(), at)] = (kind, size, first if kind == 'realloc' else None,
                                                        self.user_frame(caller))
            return True
        return False

    def return_stop(self, thread):
        frame = thread.GetFrameAtIndex(0)
        key = (thread.GetThreadID(), frame.GetPC(), frame.GetCFA())
        returned = self.returning.pop(key, None)
        if returned:
            self.live_frames.difference_update(returned)
            for gone in returned:
                self.ownership.pop(gone, None)
                self.frame_lines.pop(gone, None)
            return True
        return False

    # Rust ownership: apply the MIR events of each line this frame finished.
    def advance(self, key, line):
        state = self.ownership.setdefault(key, {})
        previous = self.frame_lines.get(key)
        # A line with several breakpoint locations stops more than once before it finishes.
        if previous is not None and previous != line:
            self.apply(state, self.moves.get(str(previous), []))
        self.frame_lines[key] = line
        return state

    @staticmethod
    def apply(state, events, until_call=None):
        for event in events:
            if event[0] == 'call':
                if until_call is not None and event[1] == until_call:
                    return True
                continue
            kind, binding, field = event
            entry = state.setdefault(binding, {'moved': False, 'fields': set()})
            if kind == 'move':
                entry['moved'] = True
            elif kind == 'init':
                entry['moved'] = False
                entry['fields'] = set()
            elif kind == 'move_field':
                entry['fields'].add(field)
            elif kind == 'init_field':
                entry['fields'].discard(field)
        return until_call is None

    def binding_state(self, key, line, callee):
        """State of this frame's bindings at this stop; a caller paused mid-line has moved its call arguments."""
        state = {name: {'moved': v['moved'], 'fields': set(v['fields'])} for name, v in self.ownership.get(key, {}).items()}
        if callee:
            pending = {}
            if self.apply(pending, self.moves.get(str(line), []), callee):
                for name, entry in pending.items():
                    merged = state.setdefault(name, {'moved': False, 'fields': set()})
                    merged['moved'] |= entry['moved']
                    merged['fields'] |= entry['fields']
        return state

    def values(self, frame):
        line = frame.GetLineEntry().GetLine()
        out = []
        for value in frame.GetVariables(True, True, True, True):
            declaration = value.GetDeclaration()
            kind = value.GetValueType()
            this = kind == lldb.eValueTypeVariableArgument and value.GetName() == 'this'
            if not this and (not declaration.IsValid() or declaration.GetFileSpec().GetFilename() != self.source_name):
                continue
            argument = kind == lldb.eValueTypeVariableArgument
            global_ = kind in (lldb.eValueTypeVariableGlobal, lldb.eValueTypeVariableStatic)
            if not argument and not global_ and declaration.GetLine() >= line:
                continue
            if self.rust and not value.GetName():
                continue
            out.append(value)
        return out

    def heap_view(self, address, pointee, heap, names, depth):
        for start, (size, serial, _) in self.blocks.items():
            if start <= address < start + size:
                width = pointee.GetByteSize()
                if not width or pointee.GetTypeClass() & lldb.eTypeClassFunction:
                    return ['C_NOTE', '주소만 확인할 수 있는 포인터예요']
                offset = address - start
                available = (size - offset) // width
                if available == 1:
                    child = self.target.CreateValueFromAddress('item', lldb.SBAddress(address, self.target), pointee)
                    encoded = self.encode(child, heap, names, depth + 1)
                    if isinstance(encoded, list) and encoded[0] == 'REF':
                        return encoded
                hid = self.object_id(('allocation', serial, offset, self.type_key(pointee)))
                if hid not in heap:
                    heap[hid] = ['ARRAY', self.pretty(pointee.GetName())]
                    count = min(available, MAX_CHILDREN)
                    self.truncated |= available > MAX_CHILDREN
                    items = []
                    for index in range(count):
                        child = self.target.CreateValueFromAddress(
                            'item', lldb.SBAddress(address + index * width, self.target), pointee)
                        items.append(self.encode(child, heap, names, depth + 1))
                    heap[hid] = ['INSTANCE', f'동적 할당 · {self.pretty(pointee.GetName())} · +{offset}바이트',
                                 *[[f'[{index}]', item] for index, item in enumerate(items)]]
                return ['REF', int(hid)]
        if any(start <= address < start + size for start, (size, _, _) in self.freed.items()):
            return ['C_NOTE', f'0x{address:x} · 해제된 동적 메모리']
        return None

    def pointer(self, address, pointee, heap, names, depth):
        if not address:
            return None
        named = names.get((address, self.type_key(pointee)))
        if named:
            return ['C_PTR', named]
        if not self.rust:
            seen = self.heap_view(address, pointee, heap, names, depth)
            if seen:
                return seen
            if pointee.GetTypeClass() & (lldb.eTypeClassStruct | lldb.eTypeClassClass):
                hid = self.object_id(('object', address, self.type_key(pointee)))
                if hid in heap:
                    return ['REF', int(hid)]
            return ['C_NOTE', f'0x{address:x} · 대상 범위를 몰라 따라가지 않아요']
        # Safe Rust references and Boxes always point at a live value of their type.
        if pointee.GetName() in ('str', 'mut str'):
            return ['C_NOTE', '문자열 조각']
        child = self.target.CreateValueFromAddress('item', lldb.SBAddress(address, self.target), pointee)
        value = self.encode(child, heap, names, depth + 1)
        if isinstance(value, list) and value[0] == 'REF':
            return value
        hid = self.object_id(('object', address, self.type_key(pointee)))
        heap[hid] = ['INSTANCE', self.pretty(pointee.GetName()), ['값', value]]
        return ['REF', int(hid)]

    def text_of(self, value):
        """String contents read from the process: Rust String/&str bytes or the C++ string LLDB formats."""
        if self.rust:
            count = value.GetNumChildren()
            if not count:
                return ''
            address = value.GetChildAtIndex(0).GetLoadAddress()
            error = lldb.SBError()
            data = self.process.ReadMemory(address, min(count, 4096), error)
            if error.Fail():
                return None
            return data.decode('utf-8', 'replace')
        return _unquote(value.GetSummary())

    def container(self, value, typ):
        if typ.GetTypeClass() & (lldb.eTypeClassPointer | lldb.eTypeClassReference):
            return None
        name = self.type_key(typ)
        if self.rust:
            if name == 'alloc::string::String':
                return 'string'
            if name in ('&str', '&mut str'):
                return 'str'
            if name.startswith('alloc::vec::Vec<') or name.startswith('alloc::collections::vec_deque::VecDeque<'):
                return 'vec'
            raw = value.GetNonSyntheticValue()
            if raw.GetNumChildren() and raw.GetChildAtIndex(0).GetName() == '$variants$':
                return 'enum'
            return None
        if re.match(r'std::(__cxx11::|__1::)?basic_string<char,', name):
            return 'cppstring'
        if re.match(r'std::(__1::)?(vector|array|deque|list)<', name):
            return 'vec'
        if re.match(r'std::(__1::|__detail::)?(unique_ptr|shared_ptr|__unique_ptr_t)<', name) or 'unique_ptr<' in name:
            return 'smart'
        return None

    def encode(self, value, heap, names, depth=0, state=None):
        if depth > 6 or not value.IsValid() or value.GetError().Fail():
            return ['C_NOTE', '값을 읽을 수 없어요']
        typ = value.GetType().GetCanonicalType()
        type_class = typ.GetTypeClass()
        kind = self.container(value, typ)
        address = value.GetLoadAddress()
        if kind in ('string', 'str'):
            text = self.text_of(value)
            if text is None:
                return ['C_NOTE', '문자열 메모리를 읽을 수 없어요']
            if kind == 'str' or not value.GetNumChildren():
                return text
            buffer = value.GetChildAtIndex(0).GetLoadAddress()
            hid = self.object_id(('buffer', buffer, 'u8'))
            heap[hid] = ['STRING', text]
            return ['REF', int(hid)]
        if kind == 'cppstring':
            text = self.text_of(value)
            return text if text is not None else ['C_NOTE', 'std::string 값을 읽을 수 없어요']
        if kind == 'vec':
            count = value.GetNumChildren()
            first = value.GetChildAtIndex(0).GetLoadAddress() if count else lldb.LLDB_INVALID_ADDRESS
            hid = self.object_id(('buffer', first, self.type_key(typ)) if count else ('object', address, self.type_key(typ)))
            if hid not in heap:
                heap[hid] = ['ARRAY', self.pretty(value.GetTypeName())]
                children = [value.GetChildAtIndex(i) for i in range(min(count, MAX_CHILDREN))]
                self.truncated |= count > MAX_CHILDREN
                heap[hid] = ['ARRAY', self.pretty(value.GetTypeName()), *[self.encode(c, heap, names, depth + 1) for c in children]]
            return ['REF', int(hid)]
        if kind == 'smart':
            inner = value.GetChildMemberWithName('pointer')
            if not inner.IsValid():
                inner = value.GetChildAtIndex(0)
            pointee = inner.GetType().GetCanonicalType().GetPointeeType()
            if not inner.IsValid() or not pointee.IsValid():
                return ['C_NOTE', f'{self.pretty(value.GetTypeName())} 내부를 읽을 수 없어요']
            return self.pointer(inner.GetValueAsUnsigned(), pointee, heap, names, depth)
        if kind == 'enum':
            summary = value.GetSummary() or ''
            variant = re.match(r'[A-Za-z_][A-Za-z0-9_]*', summary)
            hid = self.object_id(('object', address, self.type_key(typ)))
            if hid not in heap:
                heap[hid] = ['INSTANCE', self.pretty(value.GetTypeName())]
                fields = [[c.GetName().lstrip('_'), self.encode(c, heap, names, depth + 1)]
                          for c in (value.GetChildAtIndex(i) for i in range(min(value.GetNumChildren(), MAX_CHILDREN)))]
                label = f"{self.pretty(value.GetTypeName())}::{variant.group() if variant else '?'}"
                heap[hid] = ['INSTANCE', label, *fields]
            return ['REF', int(hid)]
        if type_class & (lldb.eTypeClassPointer | lldb.eTypeClassReference):
            pointee = typ.GetPointeeType() if type_class & lldb.eTypeClassPointer else typ.GetDereferencedType()
            if type_class & lldb.eTypeClassReference:
                address_value = value.GetNonSyntheticValue().GetValueAsUnsigned() or value.Dereference().GetLoadAddress()
            else:
                address_value = value.GetValueAsUnsigned()
            return self.pointer(address_value, pointee, heap, names, depth)
        if type_class & (lldb.eTypeClassArray | lldb.eTypeClassStruct | lldb.eTypeClassClass | lldb.eTypeClassUnion):
            if type_class & lldb.eTypeClassUnion:
                return ['C_NOTE', 'union은 어느 필드가 활성인지 알 수 없어요']
            hid = self.object_id(('object', address, self.type_key(typ)))
            if hid not in heap:
                heap[hid] = ['ARRAY', self.pretty(value.GetTypeName())]
                count = value.GetNumChildren()
                children = [value.GetChildAtIndex(i) for i in range(min(count, MAX_CHILDREN))]
                self.truncated |= count > MAX_CHILDREN
                if type_class & lldb.eTypeClassArray:
                    heap[hid] = ['ARRAY', self.pretty(value.GetTypeName()), *[self.encode(c, heap, names, depth + 1) for c in children]]
                else:
                    moved = state['fields'] if state else set()
                    heap[hid] = ['INSTANCE', self.pretty(value.GetTypeName()),
                                 *[[(c.GetName() or '').lstrip('_') if self.rust else c.GetName(),
                                    ['C_NOTE', MOVED] if index in moved else self.encode(c, heap, names, depth + 1)]
                                   for index, c in enumerate(children)]]
            return ['REF', int(hid)]
        basic = typ.GetBasicType()
        if basic == lldb.eBasicTypeBool:
            return bool(value.GetValueAsUnsigned())
        if basic == lldb.eBasicTypeLongDouble:
            raw = value.GetValue()
            return ['SPECIAL_FLOAT', raw] if raw is not None else ['C_NOTE', 'long double 값을 읽을 수 없어요']
        if basic in (lldb.eBasicTypeFloat, lldb.eBasicTypeDouble):
            try:
                number = float(value.GetValue())
                return number if math.isfinite(number) else ['SPECIAL_FLOAT', str(number)]
            except (TypeError, ValueError):
                return ['C_NOTE', value.GetValue() or '값을 읽을 수 없어요']
        if self.rust and basic == lldb.eBasicTypeChar32:
            return ['CHAR', chr(value.GetValueAsUnsigned())]
        if not self.rust and basic in (lldb.eBasicTypeChar, lldb.eBasicTypeSignedChar, lldb.eBasicTypeUnsignedChar):
            return ['CHAR', chr(value.GetValueAsUnsigned() & 255)]
        if type_class & (lldb.eTypeClassBuiltin | lldb.eTypeClassEnumeration):
            if value.GetByteSize() > 8:
                raw = value.GetValue()
                return ['LONG', raw] if raw is not None else ['C_NOTE', f'{value.GetTypeName()} 값을 읽을 수 없어요']
            if type_class & lldb.eTypeClassEnumeration and value.GetValue() and not re.match(r'-?\d', value.GetValue()):
                hid = self.object_id(('object', value.GetLoadAddress(), self.type_key(typ)))
                heap[hid] = ['INSTANCE', f'{self.pretty(value.GetTypeName())}::{value.GetValue()}']
                return ['REF', int(hid)]
            signed = bool(typ.GetTypeFlags() & lldb.eTypeIsSigned)
            number = value.GetValueAsSigned() if signed else value.GetValueAsUnsigned()
            return ['LONG', str(number)] if abs(number) > (1 << 53) - 1 else number
        return ['C_NOTE', f'{self.pretty(value.GetTypeName())} 형식은 아직 그리지 않아요']

    def snapshot(self, thread):
        frames = [frame for frame in thread if self.user_frame(frame)]
        if not frames or self.in_prologue(thread.GetFrameAtIndex(0)) or self.early(frames[0]):
            return None
        frames.reverse()
        grouped = self.grouped(frames)
        frames = [frame for frame, _ in grouped]
        keys = [key for _, key in grouped]
        collected = [(frame, self.values(frame)) for frame in frames]
        names = {}

        def named_cells(value, name, depth=0):
            address = value.GetLoadAddress()
            if address != lldb.LLDB_INVALID_ADDRESS:
                names[(address, self.type_key(value.GetType()))] = name
            typ = value.GetType().GetCanonicalType()
            if depth >= 5 or self.container(value, typ) or not typ.GetTypeClass() & (
                    lldb.eTypeClassArray | lldb.eTypeClassStruct | lldb.eTypeClassClass):
                return
            for index in range(min(value.GetNumChildren(), MAX_CHILDREN)):
                child = value.GetChildAtIndex(index)
                suffix = f'[{index}]' if typ.GetTypeClass() & lldb.eTypeClassArray else '.' + (child.GetName() or '').lstrip('_')
                named_cells(child, name + suffix, depth + 1)

        for frame, values in collected:
            for value in values:
                if not (self.rust and value.GetValueType() == lldb.eValueTypeVariableArgument and value.GetType().IsReferenceType()):
                    named_cells(value, value.GetName())
        heap, stack, live, globals_ = {}, [], set(), {}
        for position, (frame, values) in enumerate(collected):
            key = keys[position]
            line = frame.GetLineEntry().GetLine()
            live.add(key)
            if key not in self.live_frames:
                self.frame_ids[key] = self.next_frame
                self.next_frame += 1
                self.ownership.pop(key, None)
                self.frame_lines.pop(key, None)
            top = position == len(collected) - 1
            callee = None if top else self.short_name(collected[position + 1][0])
            if self.rust:
                if top:
                    self.advance(key, line)
                state = self.binding_state(key, line, callee)
            else:
                state = {}
            locals_ = []
            for value in values:
                if value.GetValueType() == lldb.eValueTypeVariableGlobal:
                    globals_[value.GetName()] = self.encode(value, heap, names)
                else:
                    locals_.append(value)
            encoded, order = {}, []
            latest = {}
            for value in locals_:
                latest[value.GetName()] = max(latest.get(value.GetName(), 0), value.GetDeclaration().GetLine())
            for value in locals_:
                declared = value.GetDeclaration().GetLine()
                label = value.GetName()
                if declared < latest[label]:
                    label = f'{label} · 가려짐({declared}행)'
                key_name = f'{value.GetName()}@{declared}'
                binding = state.get(key_name)
                if key_name in self.hidden:
                    continue
                if binding and binding['moved']:
                    encoded[label] = ['C_NOTE', MOVED]
                else:
                    encoded[label] = self.encode(value, heap, names, state=binding)
                order.append(label)
            uninitialized = [value.GetName() for value in locals_
                             if value.GetValueType() != lldb.eValueTypeVariableArgument
                             and self.declarations.get(f'{value.GetDeclaration().GetLine()}:{value.GetName()}') is False]
            stack.append({'func_name': self.short_name(frame), 'frame_id': self.frame_ids[key],
                          'line': line, 'is_highlighted': False,
                          'encoded_locals': encoded, 'ordered_varnames': order,
                          'declared_without_initializer': uninitialized,
                          'static_names': [v.GetName() for v in locals_ if v.GetValueType() == lldb.eValueTypeVariableStatic]})
        stack[-1]['is_highlighted'] = True
        represented = {key[1] for key, hid in self.view_ids.items() if key[0] == 'allocation' and str(hid) in heap}
        shown = 0
        for address, (size, serial, user) in self.blocks.items():
            if not user or serial in represented:
                continue
            if shown >= MAX_CHILDREN:
                self.truncated = True
                break
            shown += 1
            hid = self.object_id(('allocation-metadata', serial))
            heap[hid] = ['INSTANCE', '동적 할당 · 자료형 미확인',
                         ['주소', f'0x{address:x}'], ['바이트 수', size],
                         ['상태', ['C_NOTE', '현재 포인터에서 자료형을 확인하지 못했어요']]]
        top = frames[-1]
        event = 'call' if keys[-1] not in self.live_frames else 'step_line'
        caller = thread.GetFrameAtIndex(1)
        if event == 'call' and self.user_frame(caller):
            at = caller.GetPC()
            key = (thread.GetThreadID(), at, caller.GetCFA())
            self.returning.setdefault(key, set()).add(keys[-1])
            if at not in self.return_addresses:
                self.target.BreakpointCreateByAddress(at)
                self.return_addresses.add(at)
        self.live_frames = live
        return {'event': event, 'line': top.GetLineEntry().GetLine(), 'func_name': self.short_name(top),
                'stdout': _read(os.path.join(self.case, 'trace-stdout.txt')), 'globals': globals_,
                'ordered_globals': list(globals_), 'stack_to_render': stack, 'heap': heap}

    def grouped(self, frames):
        """(frame, key) outermost first. Apple clang's complete-object constructor/destructor calls the base-object
        variant on the same line; the pair is one source-level call, kept under the outer frame's identity."""
        out = []
        for frame in frames:
            name = self.short_name(frame)
            if (out and not self.rust and self.short_name(out[-1][0]) == name
                    and re.fullmatch(r'(?:.*::)?(\w+)::~?\1', name)):
                out[-1] = (frame, out[-1][1])
            else:
                out.append((frame, (frame.GetFunctionName(), frame.GetCFA())))
        return out

    def early(self, frame):
        """rustc can attribute a frame's first instruction to a later line; that stop is before the body starts."""
        if not self.rust or (frame.GetFunctionName(), frame.GetCFA()) in self.live_frames:
            return False
        entry = self.entries.get(str(self.start_line(frame)))
        return entry is not None and frame.GetLineEntry().GetLine() > entry

    def in_prologue(self, frame):
        function = frame.GetFunction()
        if not function.IsValid():
            return False
        start = function.GetStartAddress().GetLoadAddress(self.target)
        return start <= frame.GetPC() < start + function.GetPrologueByteSize()

    def short_name(self, frame):
        name = frame.GetDisplayFunctionName() or frame.GetFunctionName() or '?'
        if self.rust:
            name = re.sub(r'::h[0-9a-f]{16}$', '', name)
            for escaped, plain in (('$u7b$', '{'), ('$u7d$', '}'), ('$LT$', '<'), ('$GT$', '>'), ('$u20$', ' '),
                                   ('$C$', ','), ('$RF$', '&'), ('$BP$', '*'), ('..', '::')):
                name = name.replace(escaped, plain)
            name = re.sub(r'::_(?=\{)', '::', name)
            parts = name.split('::')
            return '::'.join(parts[1:]) if len(parts) > 1 else name
        return re.sub(r'\(.*\)$', '', name)


def trace(debugger, command, result, internal_dict):
    case, language, source_name = shlex.split(command)
    case = os.path.abspath(case)
    source = _read(os.path.join(case, source_name))
    target = debugger.CreateTarget(os.path.join(case, 'main'))
    debugger.SetAsync(False)
    recorder = Recorder(target, case, language, source_name)
    for line in range(1, len(source.splitlines()) + 1):
        target.BreakpointCreateByLocation(os.path.join(case, source_name), line)
    info = target.GetLaunchInfo()
    info.SetWorkingDirectory(case)
    info.SetLaunchFlags(info.GetLaunchFlags() & ~lldb.eLaunchFlagDisableASLR)
    for fd, filename, read in [(0, 'stdin.txt', True), (1, 'trace-stdout.txt', False), (2, 'trace-stderr.txt', False)]:
        info.AddOpenFileAction(fd, os.path.join(case, filename), read, not read)
    error = lldb.SBError()
    process = target.Launch(info, error)
    recorder.process = process
    doc = {'code': source, 'stdin': _read(os.path.join(case, 'stdin.txt')), 'language': language,
           'compiler': target.GetTriple() + ' · 원본 프로그램 · LLDB', 'trace': [], 'problems': [],
           'stepBudget': LIMIT, 'options': {'objects': False}, 'heapTruncated': False,
           'stdout_per_step': False, 'program_runs': 0 if error.Fail() else 1}
    try:
        if error.Fail():
            doc.update(status='unsupported', message='디버거로 프로그램을 시작하지 못했어요. ' + str(error))
        else:
            hits = 0
            while process.GetState() == lldb.eStateStopped:
                hits += 1
                if process.GetNumThreads() > 1:
                    doc.update(status='unsupported', message='여러 스레드의 실행 흐름은 아직 그리지 않아요', trace=[])
                    break
                thread = process.GetSelectedThread()
                if sum(1 for frame in thread if recorder.user_frame(frame)) > DEPTH:
                    doc.update(status='step_limit', message=f'함수 호출이 {DEPTH}단계보다 깊어 기록을 멈췄어요')
                    break
                if thread.GetStopReason() in (lldb.eStopReasonException, lldb.eStopReasonSignal):
                    doc.update(status='uncaught_exception', message=thread.GetStopDescription(512))
                    break
                if hits > HITS or len(doc['trace']) >= LIMIT:
                    doc.update(status='step_limit')
                    break
                if not recorder.allocator_stop(thread) and not recorder.return_stop(thread):
                    snapshot = recorder.snapshot(thread)
                    if snapshot:
                        doc['trace'].append(snapshot)
                process.Continue()
            if 'status' not in doc:
                doc['status'] = 'ok' if process.GetExitStatus() == 0 else 'uncaught_exception'
                if doc['status'] != 'ok':
                    doc['message'] = _read(os.path.join(case, 'trace-stderr.txt'))[-500:]
            doc['exit_code'] = process.GetExitStatus() if process.GetState() == lldb.eStateExited else None
        doc['stdout'] = _read(os.path.join(case, 'trace-stdout.txt'))
        doc['heapTruncated'] = recorder.truncated
        doc['allocator_breakpoints'] = {
            name: [target.FindBreakpointByID(bid).GetNumLocations(), target.FindBreakpointByID(bid).GetHitCount()]
            for bid, name in recorder.allocator_ids.items()}
        if doc['trace']:
            doc['trace'][-1]['stdout'] = doc['stdout']
        with open(os.path.join(case, 'native_flow.json'), 'w', encoding='utf-8') as out:
            json.dump(doc, out, ensure_ascii=False, allow_nan=False)
    finally:
        if process.IsValid() and process.GetState() != lldb.eStateExited:
            process.Kill()


def __lldb_init_module(debugger, internal_dict):
    debugger.HandleCommand('command script add -f native_lldb.trace mq-native-trace')
